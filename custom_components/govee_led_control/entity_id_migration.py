"""Conservative migration of legacy Dutch Home Assistant entity IDs.

Only the Dutch suffixes generated by earlier versions of this integration are
renamed. Registered unique IDs, user-selected friendly names, individual LED
numbers, and custom entity IDs without those suffixes are preserved.
"""

from __future__ import annotations

import logging
import re

from homeassistant.core import HomeAssistant
from homeassistant.helpers import entity_registry as er

from .const import DOMAIN

_LOGGER = logging.getLogger(__name__)

_LED_LEGACY = re.compile(r"^(?P<prefix>.+)_led_r(?P<row>\d{2})_k(?P<col>\d{2})$")
_PANEL_LEGACY = re.compile(r"^(?P<prefix>.+)_paneel_(?P<panel>\d{2})$")

_LEGACY_SUFFIXES: dict[str, dict[str, str]] = {
    "sensor": {
        "volledige_controle_via": "transport",
        "paneelindeling": "topology",
    },
    "button": {
        "alles_zwart": "clear",
        "bewezen_demo_tonen": "demo",
        "orientatie_tonen": "orientation",
        "paneelindeling_via_lan_proberen": "refresh_topology",
    },
    "switch": {
        "horizontaal_spiegelen": "flip_horizontal",
        "verticaal_spiegelen": "flip_vertical",
    },
    "select": {
        "sensorvisualisatie": "visual_style",
    },
    "number": {
        "demo_sensorniveau": "visual_level",
    },
}


def proposed_entity_id(entity_id: str) -> str | None:
    """Convert only a known, legacy Dutch suffix to a semantic English slug."""
    if "." not in entity_id:
        return None
    domain, slug = entity_id.split(".", 1)
    if domain == "light":
        if match := _LED_LEGACY.fullmatch(slug):
            return (
                f"{domain}.{match.group('prefix')}_led_"
                f"row{match.group('row')}_col{match.group('col')}"
            )
        if match := _PANEL_LEGACY.fullmatch(slug):
            return f"{domain}.{match.group('prefix')}_panel_{match.group('panel')}"
    for old_suffix, new_suffix in _LEGACY_SUFFIXES.get(domain, {}).items():
        if slug == old_suffix:
            return f"{domain}.{new_suffix}"
        if slug.endswith(f"_{old_suffix}"):
            return f"{domain}.{slug[:-len(old_suffix)]}{new_suffix}"
    return None


def migrate_legacy_entity_ids(hass: HomeAssistant, config_entry_id: str) -> int:
    """Rename safe legacy IDs before entities are created on integration setup.

    Avoid renaming entities from other integrations or IDs already chosen by the
    user. Skip collisions rather than allowing a startup failure.
    """
    registry = er.async_get(hass)
    changed = 0
    for entry in tuple(er.async_entries_for_config_entry(registry, config_entry_id)):
        if entry.platform != DOMAIN:
            continue
        target = proposed_entity_id(entry.entity_id)
        if target is None or target == entry.entity_id:
            continue
        if target in registry.entities or hass.states.get(target) is not None:
            _LOGGER.warning(
                "Skipping Govee entity ID migration %s -> %s: destination exists",
                entry.entity_id,
                target,
            )
            continue
        try:
            registry.async_update_entity(entry.entity_id, new_entity_id=target)
        except ValueError:
            _LOGGER.exception(
                "Could not migrate Govee entity ID %s to %s", entry.entity_id, target
            )
            continue
        changed += 1
        _LOGGER.debug("Migrated Govee entity ID %s -> %s", entry.entity_id, target)
    if changed:
        _LOGGER.info(
            "Migrated %s legacy Govee entity IDs to semantic names", changed
        )
    return changed
